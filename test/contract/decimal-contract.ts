export const DECIMAL_SEED = 0x51c0;
const RANDOM_CASES = 200;
const RANDOM_OPS: Op[] = ["add", "sub", "mul", "div"];

function mulberry32(seed: number): () => number {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function randomCases(): Input[] {
  const next = mulberry32(DECIMAL_SEED);
  const below = (n: number) => Math.floor(next() * n);
  const digits = (n: number) =>
    Array.from({ length: n }, () => String(below(10))).join("");
  const number = () => {
    const whole = String(BigInt(`0${digits(below(26))}`));
    const fraction = digits(below(21));
    const negative = next() < 0.3 ? "-" : "";
    return `${negative}${whole}${fraction === "" ? "" : `.${fraction}`}`;
  };

  return Array.from({ length: RANDOM_CASES }, (_, i) => {
    const op = RANDOM_OPS[i % RANDOM_OPS.length]!;
    let b = number();
    while (op === "div" && new Decimal(b).isZero()) b = number();
    return { name: `random ${i}`, op, a: number(), b };
  });
}

function outcome(c: Input): { result: string } | { error: string } {
  if (!isDecimalString(c.a) || (c.b !== undefined && !isDecimalString(c.b))) {
    return { error: "invalid" };
  }
  const a = new Decimal(c.a);
  const b = new Decimal(c.b ?? "0");
  const of = (value: Decimal) => ({ result: value.toFixed() });
  switch (c.op) {
    case "parse":
      return of(a);
    case "add":
      return of(a.plus(b));
    case "sub":
      return of(a.minus(b));
    case "mul":
      return of(a.times(b));
    case "div":
      return b.isZero() ? { error: "division-by-zero" } : of(a.dividedBy(b));
    case "round":
      return of(a.toDecimalPlaces(c.places ?? 0, Decimal.ROUND_HALF_UP));
    case "compare":
      return { result: String(a.comparedTo(b)) };
    case "sign":
      return { result: a.gt(0) ? "1" : a.lt(0) ? "-1" : "0" };
  }
}

export const DECIMAL_CONTRACT_FILE = fileURLToPath(
  new URL("./decimal.json", import.meta.url),
);

export function decimalContractJson(): string {
  return `${JSON.stringify(
    {
      description:
        "Dec arithmetic: decimal.js 10, precision 40, ROUND_HALF_UP. Generated by test/contract/decimal-contract.ts; do not edit by hand.",
      cases: [...fixed, ...randomCases()].map((c) => ({ ...c, ...outcome(c) })),
    },
    null,
    2,
  )}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(DECIMAL_CONTRACT_FILE, decimalContractJson());
}
